using System;
using System.IO;
using Aspose.Pdf;
using Aspose.Pdf.Text;

class Program
{
    static void Main()
    {
        // -----------------------------------------------------------------
        // 1. Create a minimal PDF in memory (acts as the input PDF).
        // -----------------------------------------------------------------
        byte[] pdfBytes;
        using (var seedDoc = new Document())
        {
            seedDoc.Pages.Add(); // add a blank page
            using (var ms = new MemoryStream())
            {
                seedDoc.Save(ms);
                pdfBytes = ms.ToArray();
            }
        }

        // -----------------------------------------------------------------
        // 2. Load the PDF from the generated byte array.
        // -----------------------------------------------------------------
        using (var inputStream = new MemoryStream(pdfBytes))
        using (var doc = new Document(inputStream))
        {
            // Multi‑line watermark text
            const string watermarkText = "Confidential\nDo Not Distribute";

            // Custom font size and color
            const int fontSize = 36;
            var color = Color.FromRgb(1.0, 0.0, 0.0); // red

            // Apply the watermark to every page
            foreach (Page page in doc.Pages)
            {
                var stamp = new TextStamp(watermarkText)
                {
                    HorizontalAlignment = HorizontalAlignment.Center,
                    VerticalAlignment   = VerticalAlignment.Center,
                    Opacity = 0.5f,          // semi‑transparent
                    Background = true        // behind page content
                };

                // Configure appearance
                stamp.TextState.Font = FontRepository.FindFont("Helvetica");
                stamp.TextState.FontSize = fontSize;
                stamp.TextState.ForegroundColor = color;

                page.AddStamp(stamp);
            }

            // -----------------------------------------------------------------
            // 3. Save the watermarked PDF to a file (or keep it in memory).
            // -----------------------------------------------------------------
            using (var outputStream = new MemoryStream())
            {
                doc.Save(outputStream);
                File.WriteAllBytes("watermarked.pdf", outputStream.ToArray());
            }
        }
    }
}
